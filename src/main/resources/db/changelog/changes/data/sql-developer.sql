<p>Normalized databases split data into several tables to avoid duplication. To answer questions such as <em>which chapters belong to the Java Developer course</em>, rows from related tables must be combined. This is the job of <code>JOIN</code>.</p>
<h3>INNER JOIN</h3>
<p>An inner join returns only pairs of rows that satisfy the join condition. Rows without a match on the other side are excluded.</p>
<pre><code>SELECT c.name AS course, ch.order_number, ch.name AS chapter
FROM courses c
INNER JOIN chapters ch ON ch.course_id = c.id
WHERE c.name = ''Java Developer''
ORDER BY ch.order_number;</code></pre>
<p>Table aliases such as <code>c</code> and <code>ch</code> keep the query short and remove ambiguity when both tables have columns with the same name, for example <code>id</code> and <code>name</code>.</p>
<h3>LEFT JOIN</h3>
<p>A left join returns every row from the left table, and for rows without a match the columns of the right table are filled with <code>NULL</code>. It is the standard way to find missing relationships, for example courses that have no chapters yet:</p>
<pre><code>SELECT c.name
FROM courses c
LEFT JOIN chapters ch ON ch.course_id = c.id
WHERE ch.id IS NULL;</code></pre>
<p><code>RIGHT JOIN</code> is the mirror image and <code>FULL JOIN</code> keeps unmatched rows from both sides. In practice most queries are written with inner and left joins.</p>
<h3>Joining several tables</h3>
<p>Joins can be chained: courses to chapters, chapters to lessons. Each join needs its own condition. Forgetting a condition produces a Cartesian product, where every row is combined with every other row, which is a common cause of duplicated results.</p>
<h3>Aggregation</h3>
<p>Aggregate functions <code>COUNT</code>, <code>SUM</code>, <code>AVG</code>, <code>MIN</code> and <code>MAX</code> summarize groups of rows defined by <code>GROUP BY</code>. The clause <code>HAVING</code> filters groups after aggregation, while <code>WHERE</code> filters rows before it:</p>
<pre><code>SELECT c.name, COUNT(l.id) AS lessons
FROM courses c
